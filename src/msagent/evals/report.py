"""Markdown rendering of an evaluation run (the file committed to the repository)."""
from __future__ import annotations

from typing import Any


def _pct(rate: float | None) -> str:
    return "n/a" if rate is None else f"{rate * 100:.1f}%"


def render_markdown(doc: dict[str, Any], adjudications: dict[str, Any]) -> str:
    meta, s, gate = doc["meta"], doc["summary"], doc["gate"]
    lines: list[str] = []
    add = lines.append
    add("# Evaluation report")
    add("")
    add(f"- **Run:** {meta['generated_at']} · commit `{meta['commit']}` · {meta['cases_run']} cases · "
        f"{meta['duration_s']} s")
    add(f"- **Model:** `{meta['model']}` via `{meta['provider']}`")
    add(f"- **Environment clock (as-of):** {meta['as_of']} · eval file version {meta['eval_file_version']}")
    verdict = "PASSED" if gate["passed"] else "FAILED"
    add(f"- **Regression gate:** **{verdict}**" + ("" if gate["applied"] else " (subset run, not applied)"))
    add("")
    add("This file is generated by `msagent eval`. It holds verdicts and aggregates only - no answers, "
        "no member data and no expected values from the supplied pack.")
    add("")
    add("## Summary")
    add("")
    add("| Metric | Value |")
    add("|---|---|")
    add(f"| Pass rate (adjudicated - used by the gate) | {s['passed']}/{s['cases']} ({_pct(s['pass_rate'])}) |")
    a = s["as_supplied"]
    add(f"| Pass rate (expectations exactly as supplied) | {a['passed']}/{a['cases']} ({_pct(a['pass_rate'])}) |")
    add(f"| Safety-invariant violations | {s['safety_violations']} |")
    add(f"| Harness errors | {s['errors']} |")
    add(f"| Average cost per conversation | ${s['avg_cost_usd']:.5f} (max ${s['max_cost_usd']:.5f}) |")
    add(f"| Model calls per conversation (avg) | {s['avg_model_calls']} |")
    add(f"| Tokens (input / output, whole run) | {s['total_input_tokens']:,} / {s['total_output_tokens']:,} |")
    lat = s["latency"]
    add(f"| End-to-end latency per turn, p50 / p95 | {lat['turn_p50_s']} s / {lat['turn_p95_s']} s |")
    add(f"| Platform latency per turn (excl. model), p50 / p95 | {lat['platform_p50_s']} s / "
        f"{lat['platform_p95_s']} s |")
    add("")
    add("## Regression gate")
    add("")
    add("| Check | Value | Required | Result |")
    add("|---|---|---|---|")
    for c in gate["checks"]:
        result = "pass" if c["passed"] else ("**FAIL**" if c["enforced"] else "over target (reported, not enforced)")
        add(f"| {c['name']} | {c['value']} | {c['threshold']} | {result} |")
    add("")
    add("## By behaviour")
    add("")
    add("| Behaviour | Cases | Passed | Pass rate |")
    add("|---|---|---|---|")
    for name, st in s["by_behaviour"].items():
        add(f"| {name} | {st['cases']} | {st['passed']} | {_pct(st['pass_rate'])} |")
    add("")
    add("## By tenant")
    add("")
    add("| Tenant | Cases | Passed | Pass rate |")
    add("|---|---|---|---|")
    for name, st in s["by_tenant"].items():
        add(f"| {name} | {st['cases']} | {st['passed']} | {_pct(st['pass_rate'])} |")
    add("")
    add("## Adjudicated cases")
    add("")
    add("Cases where the supplied expectation conflicts with the supplied data. The gate scores the "
        "adjudicated expectation; the as-supplied result is shown above and per case below.")
    add("")
    for cid, adj in adjudications.items():
        add(f"- **{cid}** - {adj['reason']}")
    add("")
    if meta.get("kb_quarantined"):
        add("## Knowledge-base documents quarantined at ingestion")
        add("")
        for q in meta["kb_quarantined"]:
            add(f"- `{q['path']}` - {q['reason']}")
        add("")
    add("## Cases")
    add("")
    add("| Case | Tenant | Behaviour | Result | As supplied | Turns | Model calls | Latency (s) | Cost ($) | "
        "Tools | Gateway denials / guardrails | Notes |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c in doc["cases"]:
        notes = "; ".join(c["safety_violations"] + c["failures"]) or ""
        if c["adjudicated"]:
            notes = ("adjudicated. " + notes).strip()
        guards = ", ".join(c["gateway_denials"] + c["guardrails"])
        add(f"| {c['id']} | {c['tenant']} | {c['behaviour']} | {'pass' if c['passed'] else '**FAIL**'} | "
            f"{'pass' if c['passed_as_supplied'] else 'fail'} | {c['turns']} | {c['model_calls']} | "
            f"{sum(c['turn_latency_s']):.1f} | {c['cost_usd']:.5f} | {', '.join(c['tools'])} | {guards} | "
            f"{notes} |")
    add("")
    return "\n".join(lines)
